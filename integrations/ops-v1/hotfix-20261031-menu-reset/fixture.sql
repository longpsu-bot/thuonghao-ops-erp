create function pg_temp.assert_override(p_school bigint,p_ingredient bigint)
returns void language plpgsql as $$
begin
  if not exists (
    select 1 from actual_need_overrides o
    join retained_overrides r on r.school_id=o.school_id
      and r.service_date=o.service_date and r.ingredient_id=o.ingredient_id
    where o.school_id=p_school and o.ingredient_id=p_ingredient
      and to_jsonb(o)=to_jsonb(r)
  ) then
    raise exception 'saved override changed: school %, Ingredient %',p_school,p_ingredient;
  end if;
end $$;
create function pg_temp.assert_dish(p_order bigint,p_dish bigint)
returns void language plpgsql as $$
begin
  if not exists (
    select 1 from daily_order_dishes d
    join retained_dishes r on r.id=d.id
    where d.order_id=p_order and d.dish_id=p_dish and to_jsonb(d)=to_jsonb(r)
  ) then raise exception 'unchanged Dish row replaced: %/%',p_order,p_dish;
  end if;
end $$;
