-- This unchanged production trigger is the destructive side effect under test.
CREATE OR REPLACE FUNCTION pg_temp.trg_reset_actual_need_overrides_on_daily_order_dishes()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
  v_order_id         bigint;
  v_school_id        bigint;
  v_service_date     date;
  v_remaining_dishes integer;
BEGIN
  v_order_id := COALESCE(NEW.order_id, OLD.order_id);

  SELECT d.school_id, d.service_date
  INTO   v_school_id, v_service_date
  FROM   pg_temp.daily_orders d
  WHERE  d.id = v_order_id;

  IF v_school_id IS NULL OR v_service_date IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT count(*)
  INTO v_remaining_dishes
  FROM pg_temp.daily_order_dishes dod
  WHERE dod.order_id = v_order_id;

  -- If this school-date has become fully empty, wipe all non-pantry overrides
  IF COALESCE(v_remaining_dishes, 0) = 0 THEN
    DELETE FROM pg_temp.actual_need_overrides ao
    WHERE ao.school_id    = v_school_id
      AND ao.service_date = v_service_date
      AND NOT EXISTS (
        SELECT 1
        FROM pg_temp.ingredients ii
        WHERE ii.id = ao.ingredient_id
          AND ii.shopping_type_id = 3
      );

    RETURN NEW;
  END IF;

  -- Otherwise keep the existing targeted reset behavior
  WITH changed_dishes AS (
    SELECT OLD.dish_id AS dish_id
    WHERE TG_OP = 'DELETE' AND OLD.dish_id IS NOT NULL

    UNION

    SELECT NEW.dish_id
    WHERE TG_OP = 'INSERT' AND NEW.dish_id IS NOT NULL

    UNION

    SELECT OLD.dish_id
    WHERE TG_OP = 'UPDATE'
      AND OLD.dish_id IS NOT NULL
      AND NEW.dish_id IS DISTINCT FROM OLD.dish_id

    UNION

    SELECT NEW.dish_id
    WHERE TG_OP = 'UPDATE'
      AND NEW.dish_id IS NOT NULL
      AND NEW.dish_id IS DISTINCT FROM OLD.dish_id
  )
  DELETE FROM pg_temp.actual_need_overrides ao
  WHERE ao.school_id    = v_school_id
    AND ao.service_date = v_service_date
    AND ao.ingredient_id IN (
      SELECT DISTINCT ved.ingredient_id
      FROM pg_temp.v_effective_bom_dish ved
      JOIN changed_dishes cd
        ON cd.dish_id = ved.dish_id
      WHERE ved.school_id = v_school_id
    )
    AND NOT EXISTS (
      SELECT 1
      FROM pg_temp.ingredients ii
      WHERE ii.id = ao.ingredient_id
        AND ii.shopping_type_id = 3
    );

  RETURN NEW;
END;
$function$;

create trigger reset_actual_need_overrides_on_daily_order_dishes
after insert or update or delete on daily_order_dishes
for each row execute function pg_temp.trg_reset_actual_need_overrides_on_daily_order_dishes();

